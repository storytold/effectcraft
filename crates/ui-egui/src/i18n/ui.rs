//! Translations for the interface *below* the menu bar: panel labels, buttons, field names,
//! tooltips and the sentences the panels draw themselves.
//!
//! The menu bar has its own catalog in [`super`], keyed by `(command, English label)`. Text with no
//! menu command is keyed here by its English source string, so a panel can wrap a literal without
//! inventing an id, and a missing row falls back to English instead of to an empty label.
//!
//! The language in force is set once per frame, from the same resolved language the fonts are
//! installed for ([`super::language`], [`set_current`]), so a panel does not have to thread it
//! through every function. It is thread-local: the render threads never draw interface text.
//!
//! A row that carries values keeps one `{}` per value and is read with [`tr_args`]; the tests below
//! refuse a row whose placeholder count differs from its English source, so a translation can never
//! drop a value, and `tr_args` itself cannot panic.

use std::cell::Cell;
use std::collections::HashMap;
use std::fmt::Display;
use std::sync::OnceLock;

thread_local! {
    /// The resolved interface language ("en", "ja", "zh-hans", "zh-hant", "uk", "pt-br", "cs", "es"); "en" until the first
    /// frame sets it.
    static CURRENT: Cell<&'static str> = const { Cell::new("en") };
}

/// Remember the language the panels should draw in: called from the frame loop with the language
/// the fonts were installed for.
pub(crate) fn set_current(language: &'static str) {
    CURRENT.with(|c| c.set(language));
}

/// The language [`tr`] and [`tr_args`] are using.
pub(crate) fn current() -> &'static str {
    CURRENT.with(Cell::get)
}

type Index = HashMap<&'static str, &'static str>;

/// The catalog for `language`, indexed by English source (built on first use: panels translate
/// hundreds of strings a frame); `None` for English and any language that has no rows yet.
fn catalog(language: &str) -> Option<&'static Index> {
    static JA: OnceLock<Index> = OnceLock::new();
    static HANS: OnceLock<Index> = OnceLock::new();
    static HANT: OnceLock<Index> = OnceLock::new();
    static UK: OnceLock<Index> = OnceLock::new();
    static PT_BR: OnceLock<Index> = OnceLock::new();
    static CS: OnceLock<Index> = OnceLock::new();
    static ES: OnceLock<Index> = OnceLock::new();
    let (index, rows) = match language {
        "ja" => (&JA, JAPANESE),
        "zh-hans" => (&HANS, SIMPLIFIED_CHINESE),
        "zh-hant" => (&HANT, TRADITIONAL_CHINESE),
        "uk" => (&UK, UKRAINIAN),
        "pt-br" => (&PT_BR, PORTUGUESE),
        "cs" => (&CS, CZECH),
        "es" => (&ES, SPANISH),
        _ => return None,
    };
    Some(index.get_or_init(|| rows.iter().copied().collect()))
}

/// Translate one interface string: the current language's row for `text`, or `text` itself.
pub(crate) fn tr(text: &str) -> &str {
    catalog(current()).and_then(|c| c.get(text)).copied().unwrap_or(text)
}

/// Translate an interface string that carries values: each `{}` takes the next argument. A missing
/// argument leaves its placeholder out and extra ones are ignored, so this cannot panic; the tests
/// keep the placeholder count equal to the English source's.
pub(crate) fn tr_args(text: &str, args: &[&dyn Display]) -> String {
    let template = tr(text);
    let mut out = String::with_capacity(template.len() + 16);
    let mut rest = template;
    let mut n = 0;
    while let Some(at) = rest.find("{}") {
        out.push_str(&rest[..at]);
        if let Some(arg) = args.get(n) {
            out.push_str(&arg.to_string());
        }
        n += 1;
        rest = &rest[at + 2..];
    }
    out.push_str(rest);
    out
}

