#[cfg(test)]
mod tests {
    use super::Row;

    fn rows() -> Vec<&'static [Row]> {
        vec![super::SIMPLIFIED_CHINESE, super::TRADITIONAL_CHINESE]
    }

    /// A name listed twice would silently shadow the first row.
    #[test]
    fn rows_are_unique() {
        for table in rows() {
            let mut seen = std::collections::BTreeSet::new();
            for (english, _) in table {
                assert!(seen.insert(*english), "{english:?} is listed twice");
            }
        }
    }

    /// An empty translation would draw a blank where a name belongs.
    #[test]
    fn translations_are_not_empty() {
        for table in rows() {
            for (english, translated) in table {
                assert!(!english.is_empty() && !translated.is_empty());
            }
        }
    }

    /// The two Chinese catalogs carry the same names, so neither falls back to English where
    /// the other translates.
    #[test]
    fn the_chinese_catalogs_agree() {
        let simplified: Vec<&str> = super::SIMPLIFIED_CHINESE.iter().map(|(en, _)| *en).collect();
        let traditional: Vec<&str> = super::TRADITIONAL_CHINESE.iter().map(|(en, _)| *en).collect();
        assert_eq!(simplified, traditional);
    }

    /// English needs no lookup and a language with no table draws the stored name.
    #[test]
    fn english_and_untranslated_languages_fall_back() {
        assert!(super::catalog("en").is_none());
        assert!(super::catalog("zh-hans").is_some());
    }
}
