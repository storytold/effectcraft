//! Property names in the interface language.
//!
//! The property tree stores the English name: scripts, expressions, MCP and the control channel
//! match on it, and a project file stays identical whichever interface language opens it. Only
//! the *drawing* — the Timeline, Effect Controls and the pickers — goes through this catalog.
//!
//! Rows are keyed by the stored English name rather than by the property's `match_id`, because
//! one id carries different names under different parents: `rotation` is `Rotation`,
//! `Z Rotation`, `Environment Rotation` and `Segments: Rotation` in turn. The name a panel draws
//! is what a translator reads, so it is the safer key.
//!
//! A repeat (`Ellipse Path 1`) is translated whole: the index belongs to the instance, not to
//! the property, so it is carried across unchanged.

use std::collections::HashMap;
use std::sync::OnceLock;

use super::ui::current;

/// One row: the stored English name, the translation.
type Row = (&'static str, &'static str);

/// One language's catalog: its rows, indexed on first use.
struct Catalog {
    rows: &'static [Row],
    index: OnceLock<HashMap<&'static str, &'static str>>,
}

impl Catalog {
    fn translated(&self, english: &str) -> Option<&'static str> {
        self.index.get_or_init(|| self.rows.iter().copied().collect()).get(english).copied()
    }
}

/// The catalog for `language`; `None` for English, the source of every name, and for a language
/// with no table. Adding a language is one table and one arm, and no panel changes.
fn catalog(language: &str) -> Option<&'static Catalog> {
    static SIMPLIFIED: Catalog = Catalog { rows: SIMPLIFIED_CHINESE, index: OnceLock::new() };
    static TRADITIONAL: Catalog = Catalog { rows: TRADITIONAL_CHINESE, index: OnceLock::new() };
    match language {
        "zh-hans" => Some(&SIMPLIFIED),
        "zh-hant" => Some(&TRADITIONAL),
        _ => None,
    }
}

/// The property name to draw for the stored name `english`, else `english`.
pub(crate) fn name(english: &str) -> String {
    catalog(current()).and_then(|c| c.translated(english)).map_or_else(|| english.to_string(), str::to_string)
}

