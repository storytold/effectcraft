//! The layer-style records the exporter writes, one per parameter (aep-format.md 3.12b): the
//! match name, the components, the key template (`tdb4` byte 7), the class word (`tdb4` 8..11)
//! and the limits (`tdum` / `tduM`), as After Effects shows them for each style parameter. The
//! rows were listed from our style cases (950-980) through the reader.

/// One record: match name, components, key template, class word, limits.
pub(crate) type StyleRec = (&'static str, u8, u8, u32, Option<(f64, f64)>);

const fn s(name: &'static str, dims: u8, template: u8, class: u32, limits: Option<(f64, f64)>) -> StyleRec {
    (name, dims, template, class, limits)
}

