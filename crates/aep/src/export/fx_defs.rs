//! The effects the exporter writes and the parameters of each, in `parT` order: what After
//! Effects shows for an effect (its match name and name, each parameter's id, type, default, slider
//! range and valid maximum; aep-format.md 3.7). The exporter builds an effect's `parT` and value
//! group from this table (`synth`); After Effects takes the full parameter definitions from the
//! effect itself (read-back e1-zpardfull).
//!
//! The rows were listed from our effect cases (356-397 and the later effect batches) through the
//! reader; `effect_map` names the parameters the importer and exporter convert.

/// The id of the `ADBE Effect Built In Params` entry, the last of every effect.
pub(crate) const BUILT_IN: u16 = u16::MAX;

/// One parameter: its id (the `-NNNN` of its match name, not its position), its type (`pard`
/// code: 0 layer, 1 integer slider, 2 fixed slider, 3 angle, 4 checkbox, 5 colour, 6 point, 7
/// popup, 9 no data, 10 float slider, 11 arbitrary data, 12 path, 13 / 14 group start / end, 15
/// button), its default in stored units, its slider range and its valid maximum.
#[derive(Clone, Copy, Debug)]
pub(crate) struct PDef {
    pub id: u16,
    pub code: u8,
    pub default: &'static [f64],
    pub range: Option<(f64, f64)>,
    pub valid_max: Option<f64>,
    /// The valid minimum of a slider.
    pub valid_min: Option<f64>,
    /// The display word of a slider: the decimals and the percent switch (fixed and integer
    /// `pard@144`, float `pard@124`: aep-format.md 3.7); of a popup, its item count.
    pub display: u32,
}

/// One effect.
#[derive(Clone, Copy, Debug)]
pub(crate) struct FxDef {
    pub match_name: &'static str,
    /// The effect's name (`fnam`).
    pub name: &'static str,
    pub params: &'static [PDef],
}

impl FxDef {
    /// The match name of parameter `p` (`ADBE Tint-0003`).
    pub fn record(&self, p: &PDef) -> String {
        if p.id == BUILT_IN { "ADBE Effect Built In Params".to_string() } else { format!("{}-{:04}", self.match_name, p.id) }
    }
}

const fn p(id: u16, code: u8, default: &'static [f64], range: Option<(f64, f64)>, valid_max: Option<f64>, valid_min: Option<f64>, display: u32) -> PDef {
    PDef { id, code, default, range, valid_max, valid_min, display }
}

const fn fx(match_name: &'static str, name: &'static str, params: &'static [PDef]) -> FxDef {
    FxDef { match_name, name, params }
}

