/// Vendor About/System Profile diagnostics only; altered or animated values remain losses.
pub(crate) fn inert_diagnostic(effect_id: &str, raw: &str, value: &serde_json::Value, keyed: bool, expressed: bool) -> bool {
    if keyed || expressed {
        return false;
    }
    if effect_id == "ec.perspective.ccsphere" {
        // AE's unchanged defaults: XYZ rotation and disabled environment/shadow/falloff.
        // The active Metal control and selected Reflection Map remain accounted for.
        return matches!(
            (raw, value.as_f64()),
            ("CC Sphere-0026", Some(1.0)) | ("CC Sphere-0021", Some(0.0)) | ("CC Sphere-0023", Some(0.0)) | ("CC Sphere-0024", Some(0.0))
        );
    }
    let _ = value;
    false
}

/// These exact AE effects expose expression controls and do not render pixels.
pub(crate) fn control_only(ae_match: &str) -> bool {
    matches!(ae_match, "ADBE CM CropEdges" | "ADBE CM LightLeaksRandom" | "ADBE CM WigglePosition")
}

